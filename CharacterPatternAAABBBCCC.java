public class CharacterPatternAAABBBCCC {
    public static void main(String[] args)
    {
        for(char i = 'A'; i <= 'C'; i++)
        {
            for(char j = 'A'; j <= 'C'; j++)
            {
                System.out.print(" " +i+ " ");
            }
        System.out.println();
        }

    }
}
