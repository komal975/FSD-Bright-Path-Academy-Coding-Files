public class ComparisionOperators {
    public static void main(String[] args)
    {
        int a = 10;
        int b = 20;
        System.out.println(a == b);
        
        System.out.println(a >= b);

        System.out.println(a <= b);

        System.out.println( 10 != 10);

        //System.out.println(true > 10);

        System.out.println('0' > b);
    }
}
