public class TypeCasting {
    public static void main(String[] args)
    {
        byte b = 120;
        int a = b;
        System.out.println(a);

        int c = 150;
        byte d = (byte)c;
        System.out.println(d);

        int e = 130;
        byte f = (byte)e;
        System.out.println(f);

        
        int g = 343;
        byte h = (byte)g;
        System.out.println(h);

        
        int i = 178;
        byte j = (byte)i;
        System.out.println(j);

        
        int k = 234;
        byte l = (byte)k;
        System.out.println(l);

        
        int m = 758;
        byte n = (byte)m;
        System.out.println(n);
    }
    
}
